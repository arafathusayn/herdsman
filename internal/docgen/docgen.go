// Package docgen renders the reference pages under docs/ from what the binary
// says about itself, so that a page cannot disagree with the program.
package docgen

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	cliv1 "github.com/arafathusayn/herdsman/sdk/cli/v1"
	"google.golang.org/protobuf/encoding/protojson"
)

const (
	generatedNote = "<!-- Generated by make docs. Change the source it names and regenerate. -->"
	indexPage     = "index.md"
)

var verbName = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)

// CommandPages renders one page per verb in the output of `spec cli`, plus an
// index of them, keyed by file name.
func CommandPages(cliJSON []byte) (map[string]string, error) {
	spec := &cliv1.CliSpec{}
	if err := protojson.Unmarshal(cliJSON, spec); err != nil {
		return nil, fmt.Errorf("read the command spec: %w", err)
	}
	if len(spec.GetCommands()) == 0 {
		return nil, errors.New("the command spec lists no commands")
	}
	verbs := append([]*cliv1.CommandSpec{}, spec.GetCommands()...)
	sort.Slice(verbs, func(i, j int) bool { return verbs[i].GetName() < verbs[j].GetName() })
	pages := make(map[string]string, len(verbs)+1)
	var index strings.Builder
	fmt.Fprintf(&index, "# Commands\n\n%s\n\nGenerated from `herdsman spec cli`.\n\n", generatedNote)
	for _, verb := range verbs {
		name := verb.GetName()
		if !verbName.MatchString(name) || name+".md" == indexPage {
			return nil, fmt.Errorf("command name %q cannot name a page", name)
		}
		pages[name+".md"] = commandPage(verb)
		fmt.Fprintf(&index, "- [`%s`](%s.md): %s\n", name, name, verb.GetSummary())
	}
	pages[indexPage] = index.String()
	return pages, nil
}

func commandPage(verb *cliv1.CommandSpec) string {
	var page strings.Builder
	fmt.Fprintf(&page, "# herdsman %s\n\n%s\n", verb.GetName(), generatedNote)
	if summary := verb.GetSummary(); summary != "" {
		fmt.Fprintf(&page, "\n%s\n", summary)
	}
	writeHelp(&page, verb.GetHelp())
	for _, sub := range verb.GetSubcommands() {
		fmt.Fprintf(&page, "\n## herdsman %s %s\n", verb.GetName(), sub.GetName())
		writeHelp(&page, sub.GetHelp())
	}
	return page.String()
}

func writeHelp(page *strings.Builder, help string) {
	help = strings.TrimRight(help, "\n")
	if help == "" {
		return
	}
	fence := strings.Repeat("`", longestBacktickRun(help)+1)
	if len(fence) < 3 {
		fence = "```"
	}
	fmt.Fprintf(page, "\n%stext\n%s\n%s\n", fence, help, fence)
}

func longestBacktickRun(text string) int {
	longest, run := 0, 0
	for _, r := range text {
		if r != '`' {
			run = 0
			continue
		}
		run++
		longest = max(longest, run)
	}
	return longest
}

// Write puts the pages under dir and removes the page of any verb that no
// longer exists. Only Markdown files in the commands folder are generated.
func Write(dir string, commands map[string]string, config string) error {
	commandsDir := filepath.Join(dir, "commands")
	if err := os.MkdirAll(commandsDir, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(commandsDir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		_, keep := commands[entry.Name()]
		if keep || entry.IsDir() || filepath.Ext(entry.Name()) != ".md" {
			continue
		}
		if err := os.Remove(filepath.Join(commandsDir, entry.Name())); err != nil {
			return err
		}
	}
	for name, page := range commands {
		if err := os.WriteFile(filepath.Join(commandsDir, name), []byte(page), 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(dir, "config.md"), []byte(config), 0o644)
}
