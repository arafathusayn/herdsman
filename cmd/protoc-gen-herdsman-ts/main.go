// Command protoc-gen-herdsman-ts generates the TypeScript SDK's types: one
// interface per message in the shape protojson puts on the wire, and a table of
// each service's methods for createClient. It emits no runtime code beyond
// those tables, so the SDK stays free of dependencies.
package main

import (
	"fmt"
	"path"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const wellKnownPackage = "google.protobuf"

func main() {
	protogen.Options{}.Run(generate)
}

// generate writes one TypeScript file for every requested contract.
func generate(gen *protogen.Plugin) error {
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	for _, file := range gen.Files {
		if !file.Generate {
			continue
		}
		if err := generateFile(gen, file); err != nil {
			return err
		}
	}
	return nil
}

func modulePath(file protoreflect.FileDescriptor) string {
	return strings.TrimSuffix(file.Path(), ".proto")
}

// importAlias is the namespace another contract's types are imported under; the
// whole path keeps same-named messages of two packages apart.
func importAlias(file protoreflect.FileDescriptor) string {
	return strings.NewReplacer("/", "_", ".", "_", "-", "_").Replace(modulePath(file))
}

func generateFile(gen *protogen.Plugin, file *protogen.File) error {
	g := gen.NewGeneratedFile(modulePath(file.Desc)+".ts", "")
	g.P("// Code generated by protoc-gen-herdsman-ts. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()

	var body strings.Builder
	w := &writer{file: file.Desc, out: &body, imports: map[string]protoreflect.FileDescriptor{}}
	for _, enum := range file.Enums {
		w.enum(enum)
	}
	for _, message := range file.Messages {
		if err := w.message(message); err != nil {
			return err
		}
	}
	for _, service := range file.Services {
		if err := w.service(service); err != nil {
			return err
		}
	}

	imports := file.Desc.Imports()
	wrote := false
	for i := range imports.Len() {
		imported := imports.Get(i).FileDescriptor
		if _, used := w.imports[imported.Path()]; !used {
			continue
		}
		relative, err := importPath(file.Desc, imported)
		if err != nil {
			return err
		}
		g.P(`import type * as `, importAlias(imported), ` from "`, relative, `";`)
		wrote = true
	}
	if wrote {
		g.P()
	}
	g.P(strings.TrimRight(body.String(), "\n"))
	return nil
}

func importPath(from, to protoreflect.FileDescriptor) (string, error) {
	relative, err := filepath.Rel(path.Dir(from.Path()), modulePath(to))
	if err != nil {
		return "", fmt.Errorf("%s: cannot import %s: %w", from.Path(), to.Path(), err)
	}
	relative = filepath.ToSlash(relative)
	if !strings.HasPrefix(relative, "../") {
		relative = "./" + relative
	}
	return relative, nil
}

// writer holds one output file's body and the files it refers to.
type writer struct {
	file    protoreflect.FileDescriptor
	out     *strings.Builder
	imports map[string]protoreflect.FileDescriptor
}

func (w *writer) line(indent string, parts ...string) {
	w.out.WriteString(indent + strings.Join(parts, "") + "\n")
}

// comment writes a contract comment as a JSDoc block.
func (w *writer) comment(indent string, comments protogen.Comments) {
	text := strings.TrimRight(string(comments), "\n")
	if strings.TrimSpace(text) == "" {
		return
	}
	w.line(indent, "/**")
	for _, line := range strings.Split(text, "\n") {
		w.line(indent, strings.TrimRight(" * "+strings.TrimLeft(strings.ReplaceAll(line, "*/", `*\/`), " "), " "))
	}
	w.line(indent, " */")
}

func typeName(full protoreflect.FullName, file protoreflect.FileDescriptor) string {
	return strings.ReplaceAll(strings.TrimPrefix(string(full), string(file.Package())+"."), ".", "_")
}

func (w *writer) enum(enum *protogen.Enum) {
	w.comment("", enum.Comments.Leading)
	names := make([]string, 0, len(enum.Values)+1)
	for _, value := range enum.Values {
		names = append(names, strconv.Quote(string(value.Desc.Name())))
	}
	// A newer peer may send a value this build has no name for, as its number.
	names = append(names, "number")
	w.line("", "export type ", typeName(enum.Desc.FullName(), w.file), " = ", strings.Join(names, " | "), ";")
	w.line("")
}

func (w *writer) message(message *protogen.Message) error {
	if message.Desc.IsMapEntry() {
		return nil
	}
	w.comment("", message.Comments.Leading)
	w.line("", "export interface ", typeName(message.Desc.FullName(), w.file), " {")
	for _, field := range message.Fields {
		w.comment("  ", field.Comments.Leading)
		kind, err := w.fieldType(field)
		if err != nil {
			return err
		}
		w.line("  ", propertyName(field.Desc.JSONName()), "?: ", kind, ";")
	}
	w.line("", "}")
	w.line("")
	for _, enum := range message.Enums {
		w.enum(enum)
	}
	for _, nested := range message.Messages {
		if err := w.message(nested); err != nil {
			return err
		}
	}
	return nil
}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func propertyName(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return strconv.Quote(name)
}

func (w *writer) fieldType(field *protogen.Field) (string, error) {
	if field.Desc.IsMap() {
		value, err := w.singular(field.Message.Fields[1])
		if err != nil {
			return "", err
		}
		return "Record<string, " + value + ">", nil
	}
	kind, err := w.singular(field)
	if err != nil {
		return "", err
	}
	if field.Desc.IsList() {
		if strings.Contains(kind, " | ") {
			kind = "(" + kind + ")"
		}
		return kind + "[]", nil
	}
	return kind, nil
}

const floatType = `number | "NaN" | "Infinity" | "-Infinity"`

// singular is the JSON form of one value of the field.
func (w *writer) singular(field *protogen.Field) (string, error) {
	switch field.Desc.Kind() {
	case protoreflect.BoolKind:
		return "boolean", nil
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind, protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "number", nil
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return floatType, nil
	case protoreflect.StringKind, protoreflect.BytesKind,
		protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind, protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "string", nil
	case protoreflect.EnumKind:
		if field.Enum.Desc.FullName() == wellKnownPackage+".NullValue" {
			return "null", nil
		}
		return w.reference(field.Enum.Desc.ParentFile(), field.Enum.Desc.FullName()), nil
	case protoreflect.MessageKind, protoreflect.GroupKind:
		if field.Message.Desc.ParentFile().Package() == wellKnownPackage {
			return wellKnown(field.Message.Desc.FullName())
		}
		return w.reference(field.Message.Desc.ParentFile(), field.Message.Desc.FullName()), nil
	}
	return "", fmt.Errorf("%s: unsupported kind %s", field.Desc.FullName(), field.Desc.Kind())
}

func (w *writer) reference(file protoreflect.FileDescriptor, name protoreflect.FullName) string {
	local := typeName(name, file)
	if file.Path() == w.file.Path() {
		return local
	}
	w.imports[file.Path()] = file
	return importAlias(file) + "." + local
}

// wellKnown is the JSON form protojson gives the standard messages.
func wellKnown(name protoreflect.FullName) (string, error) {
	switch strings.TrimPrefix(string(name), wellKnownPackage+".") {
	case "Any":
		return `{ "@type": string; [key: string]: unknown }`, nil
	case "Timestamp", "Duration", "FieldMask":
		return "string", nil
	case "Struct":
		return "Record<string, unknown>", nil
	case "Value":
		return "unknown", nil
	case "ListValue":
		return "unknown[]", nil
	case "Empty":
		return "Record<string, never>", nil
	case "BoolValue":
		return "boolean | null", nil
	case "Int32Value", "UInt32Value":
		return "number | null", nil
	case "FloatValue", "DoubleValue":
		return floatType + " | null", nil
	case "Int64Value", "UInt64Value", "StringValue", "BytesValue":
		return "string | null", nil
	}
	return "", fmt.Errorf("%s has no JSON mapping here", name)
}

func (w *writer) service(service *protogen.Service) error {
	w.comment("", service.Comments.Leading)
	full := string(service.Desc.FullName())
	w.line("", "export const ", string(service.Desc.Name()), " = {")
	w.line("  ", "typeName: ", strconv.Quote(full), ",")
	w.line("  ", "methods: {")
	for _, method := range service.Methods {
		if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
			return fmt.Errorf("%s: streaming methods are not supported", method.Desc.FullName())
		}
		name := string(method.Desc.Name())
		w.comment("    ", method.Comments.Leading)
		w.line("    ", strings.ToLower(name[:1])+name[1:], ": {")
		w.line("      ", "path: ", strconv.Quote("/rpc/"+full+"/"+name), ",")
		request := w.reference(method.Input.Desc.ParentFile(), method.Input.Desc.FullName())
		response := w.reference(method.Output.Desc.ParentFile(), method.Output.Desc.FullName())
		w.line("      ", "signature: undefined as unknown as (request: ", request, ") => ", response, ",")
		w.line("    ", "},")
	}
	w.line("  ", "},")
	w.line("", "} as const;")
	w.line("")
	return nil
}
