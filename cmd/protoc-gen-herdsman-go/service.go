package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// The packages the generated services use.
const (
	contextPkg = protogen.GoImportPath("context")
	bytesPkg   = protogen.GoImportPath("bytes")
	fmtPkg     = protogen.GoImportPath("fmt")
	ioPkg      = protogen.GoImportPath("io")
	jsonPkg    = protogen.GoImportPath("encoding/json")
	httpPkg    = protogen.GoImportPath("net/http")
	stringsPkg = protogen.GoImportPath("strings")
	protoPkg   = protogen.GoImportPath("google.golang.org/protobuf/proto")
	rpcPkg     = protogen.GoImportPath("github.com/arafathusayn/herdsman/sdk/rpc")
)

// procedure is the HTTP path of one method.
func procedure(service *protogen.Service, method *protogen.Method) string {
	return "/rpc/" + string(service.Desc.FullName()) + "/" + string(method.Desc.Name())
}

// unary reports whether a method is neither client nor server streaming.
func unary(method *protogen.Method) bool {
	return !method.Desc.IsStreamingClient() && !method.Desc.IsStreamingServer()
}

// generateServices writes <file>_rpc.pb.go.
func generateServices(gen *protogen.Plugin, file *protogen.File) {
	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_rpc.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-herdsman-go. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	for _, service := range file.Services {
		var methods []*protogen.Method
		for _, method := range service.Methods {
			if !unary(method) {
				gen.Error(fmt.Errorf("%s: streaming methods are not supported", method.Desc.FullName()))
				return
			}
			methods = append(methods, method)
		}
		generateInterface(g, service, methods)
		generateHandler(g, service, methods)
		generateClient(g, service, methods)
		generateBinding(g, service)
	}
}

func generateInterface(g *protogen.GeneratedFile, service *protogen.Service, methods []*protogen.Method) {
	name := service.GoName
	g.P("// ", name, "Name is the service's full protobuf name.")
	g.P("const ", name, `Name = "`, service.Desc.FullName(), `"`)
	g.P()
	g.P(strings.TrimRight(service.Comments.Leading.String(), "\n"))
	g.P("type ", name, " interface {")
	for _, method := range methods {
		g.P(strings.TrimRight(method.Comments.Leading.String(), "\n"))
		g.P(method.GoName, "(", g.QualifiedGoIdent(contextPkg.Ident("Context")), ", *", g.QualifiedGoIdent(method.Input.GoIdent), ") (*", g.QualifiedGoIdent(method.Output.GoIdent), ", error)")
	}
	g.P("}")
	g.P()
}

func generateHandler(g *protogen.GeneratedFile, service *protogen.Service, methods []*protogen.Method) {
	name := service.GoName
	g.P("// New", name, "Handler serves impl over HTTP with the full binding. Mount it")
	g.P("// at the server's root or at ", rpcPkg.Ident("BasePath"), ".")
	g.P("func New", name, "Handler(impl ", name, ") ", httpPkg.Ident("Handler"), " {")
	g.P("return ", rpcPkg.Ident("NewMux"), "(")
	for _, method := range methods {
		g.P(rpcPkg.Ident("Unary"), "(", name, `Name, "`, method.Desc.Name(), `", impl.`, method.GoName, "),")
	}
	g.P(")")
	g.P("}")
	g.P()
}

func generateClient(g *protogen.GeneratedFile, service *protogen.Service, methods []*protogen.Method) {
	name := service.GoName
	client := lowerFirst(name) + "Client"
	g.P("type ", client, " struct {")
	g.P("http *", httpPkg.Ident("Client"))
	g.P("base string")
	g.P("}")
	g.P()
	g.P("// New", name, "Client calls the service at base through hc.")
	g.P("func New", name, "Client(hc *", httpPkg.Ident("Client"), ", base string) ", name, " {")
	g.P("return &", client, "{http: hc, base: ", stringsPkg.Ident("TrimRight"), `(base, "/")}`)
	g.P("}")
	g.P()
	for _, method := range methods {
		g.P("func (c *", client, ") ", method.GoName, "(ctx ", contextPkg.Ident("Context"), ", req *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
		g.P("res := new(", method.Output.GoIdent, ")")
		g.P("if err := call", name, `(ctx, c.http, c.base+"`, procedure(service, method), `", req, res); err != nil {`)
		g.P("return nil, err")
		g.P("}")
		g.P("return res, nil")
		g.P("}")
		g.P()
	}
}

// generateBinding writes the helper that carries one client call over HTTP.
func generateBinding(g *protogen.GeneratedFile, service *protogen.Service) {
	name := service.GoName
	limit := lowerFirst(name) + "MaxBody"
	g.P("// ", limit, " bounds a request or response body.")
	g.P("const ", limit, " = 4 << 20")
	g.P()
	g.P("func call", name, "(ctx ", contextPkg.Ident("Context"), ", hc *", httpPkg.Ident("Client"), ", url string, req, res ", protoPkg.Ident("Message"), ") error {")
	g.P("body, err := ", protoPkg.Ident("Marshal"), "(req)")
	g.P("if err != nil {")
	g.P("return err")
	g.P("}")
	g.P("httpReq, err := ", httpPkg.Ident("NewRequestWithContext"), "(ctx, ", httpPkg.Ident("MethodPost"), ", url, ", bytesPkg.Ident("NewReader"), "(body))")
	g.P("if err != nil {")
	g.P("return err")
	g.P("}")
	g.P(`httpReq.Header.Set("Content-Type", "application/proto")`)
	g.P("httpRes, err := hc.Do(httpReq)")
	g.P("if err != nil {")
	g.P("return err")
	g.P("}")
	g.P("defer httpRes.Body.Close()")
	g.P("data, err := ", ioPkg.Ident("ReadAll"), "(", ioPkg.Ident("LimitReader"), "(httpRes.Body, ", limit, "+1))")
	g.P("if err != nil {")
	g.P("return err")
	g.P("}")
	g.P("if len(data) > ", limit, " {")
	g.P("return ", fmtPkg.Ident("Errorf"), `("%s: response body too large", url)`)
	g.P("}")
	g.P("if httpRes.StatusCode != ", httpPkg.Ident("StatusOK"), " {")
	g.P("var failure struct {")
	g.P(`Code    string `, "`json:\"code\"`")
	g.P(`Message string `, "`json:\"message\"`")
	g.P("}")
	g.P("if err := ", jsonPkg.Ident("Unmarshal"), "(data, &failure); err != nil {")
	g.P("return ", fmtPkg.Ident("Errorf"), `("%s: HTTP %d", url, httpRes.StatusCode)`)
	g.P("}")
	g.P("return ", fmtPkg.Ident("Errorf"), `("%s: %s", failure.Code, failure.Message)`)
	g.P("}")
	g.P("return ", protoPkg.Ident("Unmarshal"), "(data, res)")
	g.P("}")
	g.P()
}

func lowerFirst(s string) string {
	return strings.ToLower(s[:1]) + s[1:]
}
